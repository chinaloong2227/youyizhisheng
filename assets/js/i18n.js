function applyLang(lang) {
  var dict = I18N[lang] || I18N.zh;
  // 同步 <html lang>，利于无障碍与 SEO
  document.documentElement.lang = (lang === 'ru') ? 'ru' : 'zh-CN';

  // 文字：data-i18n
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var k = el.getAttribute('data-i18n');
    if (dict[k] != null) el.textContent = dict[k];
  });

  // 占位符：data-i18n-ph
  document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
    var k = el.getAttribute('data-i18n-ph');
    if (dict[k] != null) el.setAttribute('placeholder', dict[k]);
  });

  // 页面描述：meta[name=description]，随语言切换，利于搜索引擎展示
  var metaDesc = document.querySelector('meta[name="description"][data-i18n-meta]');
  if (metaDesc) {
    var mk = metaDesc.getAttribute('data-i18n-meta');
    if (dict[mk] != null) metaDesc.setAttribute('content', dict[mk]);
  }

  localStorage.setItem('lang', lang);
}

function initLang() {
  var saved = localStorage.getItem('lang') || 'zh';
  applyLang(saved);
  var btn = document.getElementById('lang-toggle');
  if (btn) {
    btn.addEventListener('click', function () {
      var cur = localStorage.getItem('lang') || 'zh';
      applyLang(cur === 'zh' ? 'ru' : 'zh');
    });
  }
}

initLang();
